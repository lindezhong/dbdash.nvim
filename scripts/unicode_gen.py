"""Generate lua/dbdash/util/unicode_categories.lua (dev-only): code point ranges of each
Unicode general category, from Python's unicodedata.

    python3 -I scripts/unicode_gen.py
"""
import pathlib
import sys
import unicodedata

ranges = {}
prev = None
for cp in range(0x110000):
    cat = unicodedata.category(chr(cp))
    if cat == "Cn":
        prev = None
        continue
    lst = ranges.setdefault(cat, [])
    if prev == cat and lst and lst[-1][1] == cp - 1:
        lst[-1][1] = cp
    else:
        lst.append([cp, cp])
    prev = cat

out = [
    "-- Unicode general categories: code point ranges { lo, hi, lo, hi, ... } per category",
    f"-- (Unicode {unicodedata.unidata_version}). Generated by scripts/unicode_gen.py; do not edit.",
    "return {",
]
for cat in sorted(ranges):
    flat = []
    for lo, hi in ranges[cat]:
        flat += [str(lo), str(hi)]
    out.append(f"  {cat} = {{ {', '.join(flat)} }},")
out.append("}")
path = pathlib.Path(__file__).parent.parent / "lua" / "dbdash" / "util" / "unicode_categories.lua"
path.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {path} ({sum(len(v) for v in ranges.values())} ranges)", file=sys.stderr)
